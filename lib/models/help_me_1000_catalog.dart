  static final List<HelpMeCaseEntry> all1000 = _build1000();

  static List<HelpMeCaseEntry> _build1000() {
    final result = <HelpMeCaseEntry>[];
    int number = 1;

    // 143 * 5 + 143 + 142 = 999? Wait: 15 situations * 10 contexts = 150 per blueprint.
    // Let's allocate exact counts summing to 1000:
    // Blueprints 0..5 -> 143 each (858), blueprint 6 -> 142 => 1000! Or let's interleave round-robin across blueprints so all domains appear richly from #1 upward!
    final quotas = [143, 143, 143, 143, 143, 143, 142]; // sum = 1000
    final counters = List<int>.filled(_blueprints.length, 0);

    while (result.length < 1000) {
      for (int b = 0; b < _blueprints.length && result.length < 1000; b++) {
        if (counters[b] >= quotas[b]) continue;
        final bp = _blueprints[b];
        final localIdx = counters[b];
        counters[b]++;

        final sit = bp.situations[localIdx % bp.situations.length];
        final ctx = bp.contexts[(localIdx ~/ bp.situations.length) % bp.contexts.length];
        final ayah = bp.quranVerses[localIdx % bp.quranVerses.length];
        final hadith = bp.hadiths[(localIdx + b) % bp.hadiths.length];
        final doAct = bp.dos[localIdx % bp.dos.length];
        final dontAct = bp.donts[(localIdx + 1) % bp.donts.length];
        final altDo = bp.dos[(localIdx + 2) % bp.dos.length];
        final dua = bp.duas[localIdx % bp.duas.length];

        result.add(
          HelpMeCaseEntry(
            number: number++,
            domainId: bp.domain.id,
            domainLabel: bp.domain.label,
            subCategory: sit,
            emoji: bp.domain.emoji,
            title: '$sit — $ctx',
            summary:
                'منهج قرآني ونبوي عملي للتعامل مع «$sit» ($ctx) بالثبات والحكمة.',
            quranAyah: ayah,
            hadithReference: hadith,
            doAction: doAct,
            dontAction: dontAct,
            practicalSteps: [
              '✅ افعل (إيه أه): $doAct',
              '🚫 اجتنب (إيه لأ): $dontAct',
              '🌿 خطوة عملية إضافية: $altDo',
            ],
            dua: dua,
            primaryColor: bp.domain.primaryColor,
            accentColor: bp.domain.accentColor,
            hasBreathingGuide: bp.hasBreathing,
          ),
        );
      }
    }

    return List<HelpMeCaseEntry>.unmodifiable(result);
  }

  static String _normalizeArabic(String input) {
    return input
        .replaceAll(RegExp(r'[\u064B-\u065F\u0670\u0640]'), '')
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ى', 'ي')
        .replaceAll('ة', 'ه')
        .toLowerCase();
  }

  static List<HelpMeCaseEntry> filter({
    String domainId = 'all',
    String subCategory = 'all',
    String query = '',
  }) {
    final q = _normalizeArabic(query.trim());
    return all1000.where((e) {
      if (domainId != 'all' && e.domainId != domainId) return false;
      if (subCategory != 'all' && e.subCategory != subCategory) return false;
      if (q.isEmpty) return true;
      return _normalizeArabic(e.title).contains(q) ||
          _normalizeArabic(e.domainLabel).contains(q) ||
          _normalizeArabic(e.subCategory).contains(q) ||
          _normalizeArabic(e.summary).contains(q) ||
          _normalizeArabic(e.doAction).contains(q) ||
          _normalizeArabic(e.dontAction).contains(q) ||
          _normalizeArabic(e.quranAyah).contains(q);
    }).toList();
  }

  /// تجميع أي قائمة حالات حسب التصنيف الفرعي المرتب داخل الكتجري
  static Map<String, List<HelpMeCaseEntry>> groupBySubCategory(
    List<HelpMeCaseEntry> entries,
  ) {
    final map = <String, List<HelpMeCaseEntry>>{};
    for (final entry in entries) {
      (map[entry.subCategory] ??= <HelpMeCaseEntry>[]).add(entry);
    }
    return map;
  }

  /// التصنيفات الفرعية الفريدة التابعة لكتجري محدد
  static List<String> subCategoriesForDomain(String domainId) {
    final seen = <String>{};
    final out = <String>[];
    for (final entry in all1000) {
      if (entry.domainId == domainId && seen.add(entry.subCategory)) {
        out.add(entry.subCategory);
      }
    }
    return out;
  }
