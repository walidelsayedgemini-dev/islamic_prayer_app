import 'package:flutter/material.dart';

class HelpMeDomain {
  final String id;
  final String label;
  final String emoji;
  final Color primaryColor;
  final Color accentColor;
  final IconData icon;

  const HelpMeDomain({
    required this.id,
    required this.label,
    required this.emoji,
    required this.primaryColor,
    required this.accentColor,
    required this.icon,
  });
}

class HelpMeCaseEntry {
  final int number; // 1..1000
  final String domainId;
  final String domainLabel;
  final String subCategory;
  final String emoji;
  final String title;
  final String summary;
  final String quranAyah;
  final String hadithReference;
  final String doAction; // إيه أه ✓
  final String dontAction; // إيه لأ ✗
  final List<String> practicalSteps;
  final String dua;
  final Color primaryColor;
  final Color accentColor;
  final bool hasBreathingGuide;

  const HelpMeCaseEntry({
    required this.number,
    required this.domainId,
    required this.domainLabel,
    required this.subCategory,
    required this.emoji,
    required this.title,
    required this.summary,
    required this.quranAyah,
    required this.hadithReference,
    required this.doAction,
    required this.dontAction,
    required this.practicalSteps,
    required this.dua,
    required this.primaryColor,
    required this.accentColor,
    this.hasBreathingGuide = false,
  });
}

class _DomainBlueprint {
  final HelpMeDomain domain;
