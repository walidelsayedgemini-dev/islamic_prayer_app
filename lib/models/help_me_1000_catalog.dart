  const _DomainBlueprint({
    required this.domain,
    required this.situations,
    required this.contexts,
    required this.quranVerses,
    required this.hadiths,
    required this.dos,
    required this.donts,
    required this.duas,
    this.hasBreathing = false,
  });
}

