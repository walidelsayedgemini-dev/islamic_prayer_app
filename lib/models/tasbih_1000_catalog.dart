class TasbihDuaEntry {
  final int number; // 1..1000
  final String category;
  final String text;
  final String virtue;
  final int recommendedCount;

  const TasbihDuaEntry({
    required this.number,
    required this.category,
    required this.text,
    required this.virtue,
    this.recommendedCount = 33,
  });
}

