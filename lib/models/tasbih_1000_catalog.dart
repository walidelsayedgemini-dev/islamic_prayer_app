  static final List<TasbihDuaEntry> all1000 = _build1000();

  static String _normalizeArabic(String input) {
    return input
        .replaceAll(RegExp(r'[\u064B-\u065F\u0670\u0640]'), '')
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ى', 'ي')
        .replaceAll('ة', 'ه')
        .toLowerCase();
  }

  static List<TasbihDuaEntry> search({
    String query = '',
    String category = 'الكل',
  }) {
    final trimmed = _normalizeArabic(query.trim());
    return all1000.where((entry) {
      if (category != 'الكل' && entry.category != category) return false;
      if (trimmed.isEmpty) return true;
      return _normalizeArabic(entry.text).contains(trimmed) ||
          _normalizeArabic(entry.virtue).contains(trimmed) ||
          _normalizeArabic(entry.category).contains(trimmed);
    }).toList();
  }

