  static String formatPhrase(
    String template, {
    required String name,
    required String rival,
  }) {
    final cleanName = name.trim().isEmpty ? 'يا بطل' : name.trim();
    final cleanRival = rival.trim().isEmpty ? 'صاحبك' : rival.trim();
    return template
        .replaceAll('{name}', cleanName)
        .replaceAll('{rival}', cleanRival);
  }

  static String pickWinPhrase(
    int seed, {
    required String name,
    required String rival,
  }) {
    final idx = seed.abs() % winPhrases.length;
    return formatPhrase(winPhrases[idx], name: name, rival: rival);
  }

  static String pickLosePhrase(
    int seed, {
    required String name,
    required String rival,
  }) {
    final idx = seed.abs() % losePhrases.length;
    return formatPhrase(losePhrases[idx], name: name, rival: rival);
  }

