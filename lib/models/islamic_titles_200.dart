import 'package:flutter/material.dart';

/// نوع المهمة المطلوبة لفتح كل لقب من الألقاب الإسلامية الـ 200
enum TitleMissionType {
  prayerDaysStreak, // عدد أيام المواظبة على الصلوات الخمس كاملة
  totalPrayersLogged, // إجمالي الصلوات المسجلة في السجل
  congregationPrayers, // عدد صلوات الجماعة في المسجد
  fajrCount, // عدد صلوات الفجر المؤداة في وقتها
  qadaRecovered, // عدد الصلوات الفائتة التي تم قضاؤها
  totalDhikr, // إجمالي التسبيح والأذكار
  istighfarCount, // عدد مرات الاستغفار
  salawatCount, // عدد مرات الصلاة على النبي ﷺ
  completedMissions, // عدد المهام والطاعات الإسلامية المنجزة
  competitionsWon, // عدد المسابقات الإسلامية التي فاز بها المستخدم
  quranSurahsRead, // عدد السور المقروءة من المصحف
  journalNotesCount, // عدد الخواطر والملاحظات المكتوبة في المذكرة
  qiyamNights, // عدد ليالي القيام والوتر أو صلاة الضحى
}

class IslamicTitleEntry {
  final int number; // 1 .. 200
  final String id;
  final String titleMale;
  final String titleFemale;
  final String category;
  final String tierName;
  final Color badgeColor;
  final IconData icon;
  final TitleMissionType missionType;
  final int targetValue;
  final String missionDescription;

  const IslamicTitleEntry({
    required this.number,
    required this.id,
    required this.titleMale,
    required this.titleFemale,
    required this.category,
    required this.tierName,
    required this.badgeColor,
    required this.icon,
    required this.missionType,
    required this.targetValue,
    required this.missionDescription,
  });

  String localizedTitle({required bool isFemale}) =>
      isFemale ? titleFemale : titleMale;

  String get missionTypeLabel {
    switch (missionType) {
      case TitleMissionType.prayerDaysStreak:
        return 'أيام مواظبة على الصلاة';
      case TitleMissionType.totalPrayersLogged:
        return 'إجمالي الصلوات المسجلة';
      case TitleMissionType.congregationPrayers:
        return 'صلوات الجماعة';
      case TitleMissionType.fajrCount:
        return 'صلوات الفجر';
      case TitleMissionType.qadaRecovered:
        return 'قضاء الفوائت';
      case TitleMissionType.totalDhikr:
        return 'عدد التسبيح والذكر';
      case TitleMissionType.istighfarCount:
        return 'عدد الاستغفار';
      case TitleMissionType.salawatCount:
        return 'الصلاة على النبي ﷺ';
      case TitleMissionType.completedMissions:
        return 'المهام والطاعات المنجزة';
      case TitleMissionType.competitionsWon:
        return 'المسابقات الفائزة';
      case TitleMissionType.quranSurahsRead:
        return 'سور القرآن المقروءة';
      case TitleMissionType.journalNotesCount:
        return 'تدوينات المذكرة';
      case TitleMissionType.qiyamNights:
        return 'ليالي القيام والضحى';
    }
  }
}

