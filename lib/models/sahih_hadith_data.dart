class HadithChapter {
  final String id;
  final String title;
  final String emoji;
  final String description;

  const HadithChapter({
    required this.id,
    required this.title,
    required this.emoji,
    required this.description,
  });
}

class SahihHadithEntry {
  final String id;
  final String chapterId;
  final String title;
  final String sourceReference; // e.g. 'صحيح البخاري (1)'
  final String narrator;
  final String arabicText;
  final String sharhAndTafsir;
  final String practicalBenefit;
  final String emoji;
  final int? linkedSurah;
  final int? linkedAyah;

  const SahihHadithEntry({
    required this.id,
    required this.chapterId,
    required this.title,
    required this.sourceReference,
    required this.narrator,
    required this.arabicText,
    required this.sharhAndTafsir,
    required this.practicalBenefit,
    this.emoji = '📜',
    this.linkedSurah,
    this.linkedAyah,
  });
}

