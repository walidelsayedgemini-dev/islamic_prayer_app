  static SahihHadithEntry getById(String id) {
    return allHadiths.firstWhere(
      (h) => h.id == id,
      orElse: () => allHadiths.first,
    );
  }

  /// يبحث عن الحديث بالمعرّف أو برقم البخاري أو كلمة مفتاحية، ويعود لأقرب حديث موثق
  static SahihHadithEntry resolveReference(String referenceText) {
    final trimmed = referenceText.trim();
    for (final h in allHadiths) {
      if (h.id == trimmed || h.sourceReference.contains(trimmed)) {
        return h;
      }
    }
    // استخراج رقم صحيح البخاري أو مسلم إن وُجد في النص
    final numMatch = RegExp(r'\((\d{1,4})\)').firstMatch(trimmed);
    if (numMatch != null) {
      final numStr = numMatch.group(1)!;
      for (final h in allHadiths) {
        if (h.sourceReference.contains(numStr)) return h;
      }
    }
    // مطابقة ذكية بالعنوان أو الكلمات الأساسية
    for (final h in allHadiths) {
      if (trimmed.contains(h.title) || h.title.contains(trimmed)) {
        return h;
      }
    }
    if (trimmed.contains('الفردوس')) return getById('b_100');
    if (trimmed.contains('ريان') || trimmed.contains('صيام') || trimmed.contains('صوم')) {
      return getById('b_71');
    }
    if (trimmed.contains('موسى')) return getById('b_83');
    if (trimmed.contains('يوسف')) return getById('b_82');
    if (trimmed.contains('إبراهيم') || trimmed.contains('زمزم')) return getById('b_81');
    if (trimmed.contains('إخلاص') || trimmed.contains('ثُلث')) return getById('b_19');
    if (trimmed.contains('استغفار') || trimmed.contains('سيد')) return getById('b_37');
    if (trimmed.contains('صلاة') && trimmed.contains('وقت')) return getById('b_25');
    if (trimmed.contains('حوض') || trimmed.contains('كوثر')) return getById('b_105');
    if (trimmed.contains('ما لا عين')) return getById('b_99');
    return allHadiths.first;
  }

  static List<SahihHadithEntry> byChapter(String chapterId) {
    if (chapterId == 'all') return allHadiths;
    return allHadiths.where((h) => h.chapterId == chapterId).toList();
  }
