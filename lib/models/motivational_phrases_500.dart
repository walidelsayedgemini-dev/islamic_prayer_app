/// قاعدة بيانات الـ 500 عبارة تشجيعية الإسلامية المخصصة بالاسم والنوع
class MotivationalPhraseEntry {
  final int number; // 1 .. 500
  final String category;
  final String template;

  const MotivationalPhraseEntry({
    required this.number,
    required this.category,
    required this.template,
  });

  String format({required String name, required bool isFemale}) {
    return MotivationalPhrasesCatalog.formatPhrase(
      template,
      name: name,
      isFemale: isFemale,
    );
  }
}

