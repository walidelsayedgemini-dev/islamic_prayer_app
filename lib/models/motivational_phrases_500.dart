  static String formatPhrase(
    String template, {
    required String name,
    required bool isFemale,
  }) {
    final trimmed = name.trim();
    final safeName = trimmed.isEmpty
        ? (isFemale ? 'أختنا الفاضلة' : 'أخانا الكريم')
        : trimmed;
    var out = template.replaceAll('{name}', safeName);
    out = out.replaceAllMapped(
      RegExp(r'\[\[([^|\]]*)\|([^\]]*)\]\]'),
      (match) => isFemale ? (match.group(2) ?? '') : (match.group(1) ?? ''),
    );
    return out;
  }

