  static List<MotivationalPhraseEntry> byCategory(String category) {
    if (category == 'الكل') return allPhrases;
    return allPhrases.where((p) => p.category == category).toList();
  }

  static MotivationalPhraseEntry pickForSeed(int seed, {String category = 'الكل'}) {
    final pool = byCategory(category);
    if (pool.isEmpty) return allPhrases.first;
    final idx = seed.abs() % pool.length;
    return pool[idx];
  }

