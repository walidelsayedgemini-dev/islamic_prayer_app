      const realms = ['في الحياة اليومية', 'في سوق العمل والتجارة', 'أمام التحديات التقنية', 'في الأزمات الاقتصادية', 'عند التخطيط للمستقبل'];
      final rl = realms[lIdx % realms.length];
      pushQa(
        category: IslamicQaCategory.lifeTawbah,
        sectionTitle: sub,
        q: 'ما المنهج الشرعي المنضبط في «$lt» $rl (مسألة $k)؟',
        a: '$la ويمنح الالتزام بهذا المنهج $rl بركةً ظاهرةً في الرزق وسلامةً في الدين والضمير.',
        e: le,
        t: [lt, rl, 'المعاملات والحياة'],
      );
      lIdx++;
    }

    assert(items.length == 4500, 'Expected 4500 expansion items, got ${items.length}');
    return items;
  }
